/* command write to SSD1306 */
ret_code_t ssd_write_commands (const uint8_t *commands, uint8_t length)
{
  if (commands == NULL || length == 0) {
    return NRF_ERROR_INVALID_PARAM;
  }
  if (length > SSD_MAX_COMMAND_BYTES) {
    return NRF_ERROR_INVALID_LENGTH;
  }
  
  uint8_t buffer[1 + SSD_MAX_COMMAND_BYTES];
  
  buffer[0] = SSD_CONTROL_COMMAND;
  memcpy(&buffer[1], commands, length);
  
  nrf_twi_mngr_transfer_t transfer = 
    NRF_TWI_MNGR_WRITE(SSD_ADDR, buffer, length + 1, 0);
  
  return nrf_twi_mngr_perform(&m_twi_external, NULL, &transfer, 1, NULL);
}

static ret_code_t ssd_write_data(const uint8_t *data, uint16_t length)
{
  static uint8_t buf[SSD_CHUNK + 1];   

  if (data == NULL || length == 0)
    return NRF_ERROR_INVALID_PARAM;

  while (length > 0) {
    uint8_t n = (length > SSD_CHUNK) ? SSD_CHUNK : (uint8_t)length;

    buf[0] = SSD_CONTROL_DATA;                     
    memcpy(&buf[1], data, n);             

    nrf_twi_mngr_transfer_t data_buffer[] = {
      NRF_TWI_MNGR_WRITE(SSD_ADDR, buf, n + 1, 0)
    };

    ret_code_t err = nrf_twi_mngr_perform(&m_twi_external, NULL, data_buffer, 1, NULL);
    if (err != NRF_SUCCESS)
      return err;

    data   += n;
    length -= n;
  }
  return NRF_SUCCESS;
}

/* ssd-1306 initialization */
bool ssd_init(void)
{
  const uint8_t commands_config[] = {
        0xAE,           // Display OFF
        0xA8, 0x3F,     // mux ratio, 구동 COM 행 수 64로 설정
        0xD3, 0x00,     // Display Offset 
        0x40,           // Display Start Line
        0xA1,           // display 좌우 방향, default
        0xC8,           // display 상하 방향, default
        0xDA, 0x12,     // COM config
        0x81, 0x7F,     // Contrast
        0xA4,           // GDDRAM 내용 표시
        0xA6,           // Normal display
        0xD5, 0x80,     // Set Osc Frequency; Clock 설정
        0x8D, 0x14     // Enable charge pump regulator
    };

    const uint8_t commands_addr[] = {
        0x20, 0x00,        // Horizontal addressing
        0x21, 0x00, 0x7F,  // Column: 0~127(full)
        0x22, 0x00, 0x07   // Page: 0~7(full)
    };

    //write config commands on ssd
    if (ssd_write_commands(commands_config, sizeof(commands_config)) != NRF_SUCCESS)
        return false;
    //write addr commands on ssd
    if (ssd_write_commands(commands_addr, sizeof(commands_addr)) != NRF_SUCCESS)
        return false;

    //clear ssd gddram
    //static uint8_t zero[1024] = {0};

    //if (ssd_write_data(zero, sizeof(zero)) != NRF_SUCCESS)
    //    return false;

    //initially display logo
    if (ssd_write_data(labLogoW, sizeof(labLogoW)) != NRF_SUCCESS)
      return false;
    current_display = LOGO;

    const uint8_t display_on[] = {0xAF};

    return ssd_write_commands(display_on, sizeof(display_on)) == NRF_SUCCESS;
}

void display_time(uint8_t hour, uint8_t min, uint8_t sec)
{
  static uint8_t frame[SSD_WIDTH * SSD_PAGES];   // whole frame

  const uint8_t *time[8] = {
    digit_bitmap[hour / 10], digit_bitmap[hour % 10], colon_bitmap,
    digit_bitmap[min / 10],  digit_bitmap[min % 10],  colon_bitmap,
    digit_bitmap[sec / 10],  digit_bitmap[sec % 10]
  };

  /* display on page 3-4 with 1colum margin => start offset: (3 × 128(page)) + column 8 = 392 */
  const uint16_t base = TIME_PAGE * SSD_WIDTH + TIME_COL_START;   

  for (int i = 0; i < 8; i++) {
    uint16_t pos = base + i * DIGIT_WIDTH;

    memcpy(&frame[pos], time[i], DIGIT_WIDTH);  // page 3 
    memcpy(&frame[pos + SSD_WIDTH], time[i] + DIGIT_WIDTH, DIGIT_WIDTH);  // page 4 
  }

  ssd_write_data(frame, sizeof(frame));
}

//only display page 3,4 for fast time update
void display_time_partial(uint8_t hour, uint8_t min, uint8_t sec)
{
  static uint8_t frame[SSD_WIDTH * 2];   // 2 pages

  const uint8_t *time[8] = {
    digit_bitmap[hour / 10], digit_bitmap[hour % 10], colon_bitmap,
    digit_bitmap[min / 10],  digit_bitmap[min % 10],  colon_bitmap,
    digit_bitmap[sec / 10],  digit_bitmap[sec % 10]
  };
  
  //set update pixel address to page 3,4
  const uint8_t commands_addr[] = {
        0x20, 0x00,        // Horizontal addressing
        0x21, 0x00, 0x7F,  // Column: 0~127(full)
        0x22, 0x03, 0x04   // Page: 0~7(full)
    };
    
  //write addr commands on ssd
  if (ssd_write_commands(commands_addr, sizeof(commands_addr)) != NRF_SUCCESS){
    return;
  }

  const uint16_t base = 8;   // 1 segment margin at left

  for (int i = 0; i < 8; i++) {
    uint16_t pos = base + i * DIGIT_WIDTH;

    memcpy(&frame[pos], time[i], DIGIT_WIDTH);  // page 3 
    memcpy(&frame[pos + SSD_WIDTH], time[i] + DIGIT_WIDTH, DIGIT_WIDTH);  // page 4 
  }

  ssd_write_data(frame, sizeof(frame));
}

