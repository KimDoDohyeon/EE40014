  int8_t hour = (now / 3600U) % 24U;
  int8_t min = (now / 60U) % 60U;
  int8_t rem_sec = now % 60U;
  
  switch (mode) {
    
    case LOGO:
      ssd_write_data(labLogoW, sizeof(labLogoW));
      break;
    
    case CLOCK:
      display_time(hour,min,rem_sec);
      break;
    
    case NORMAL:
      ssd_write_commands(&disp_normal, 1);
      break;
    
    case INV:
      ssd_write_commands(&disp_inv, 1);
      break;
  }
  
